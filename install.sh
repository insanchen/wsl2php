main() {
  local arg
  for arg in "$@"; do case "$arg" in --yes) ASSUME_YES=Y ;; --dry-run) DRY_RUN=Y ;; --configure) CONFIGURE=Y ;; -h|--help) usage; exit 0 ;; *) die "Unknown option: $arg" ;; esac; done
  load_env
  if is_yes "$CONFIGURE" || { [[ ! -f $ENV_FILE ]] && ! is_yes "$ASSUME_YES" && ! is_yes "$DRY_RUN" && [[ -t 0 ]]; }; then interactive_wizard; fi
  validate_config
  preflight
  show_plan
  if is_yes "$DRY_RUN"; then printf '\nDry run complete: no system changes made.\n'; return 0; fi
  confirm_or_configure || return 0
  safe_source_private_addons
  info 'Preparing package repositories'
  root apt-get update
  root apt-get install -y ca-certificates curl gnupg lsb-release
  setup_php_repository
  root apt-get update
  package_plan
  info 'Installing system packages'
  root env DEBIAN_FRONTEND=noninteractive apt-get install -y "${PACKAGES[@]}"
  install_user_tools
  install_composer
  install_phpmyadmin
  INSTALL_NAME=localhost; [[ $SERVER_NAME != localhost ]] && INSTALL_NAME=server
  root install -d -m 0755 "$SERVER_ROOT/$SERVER_APP"
  is_yes "$INSTALL_PHP" && config_php
  is_yes "$INSTALL_NGINX" && config_nginx
  is_yes "$INSTALL_APACHE" && config_apache
  is_yes "$INSTALL_MARIADB" && config_mariadb
  is_yes "$INSTALL_REDIS" && config_redis
  is_yes "$INSTALL_PHPMYADMIN" && config_phpmyadmin
  config_environment
  safe_source_private_restore
  config_timezone
  enable_services
  safe_source_private_addons
  if [[ -f "$PRIVATE_DIR/scripts/sshclone.sh" ]]; then
    info 'Private sshclone.sh available; run it manually to sync SSH keys.'
  fi
  if is_yes "$INSTALL_NGINX"; then service_action nginx restart; fi
  if is_yes "$INSTALL_APACHE"; then service_action apache2 restart; fi
  if is_yes "$INSTALL_PHP"; then local_ver=""; for local_ver in "${INSTALL_PHP_VERSION[@]}"; do service_action "php$local_ver-fpm" restart; done; fi
  root apt-get clean
  verify_services
  ui_footer
}

main "$@"
