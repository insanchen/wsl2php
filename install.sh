#!/usr/bin/env bash
# PHP/MariaDB development installer. Safe defaults work from a public clone.
set -Eeuo pipefail
IFS=$'\n\t'

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
cd "$SCRIPT_DIR"
PRIVATE_DIR="$SCRIPT_DIR/config/private"
ENV_FILE="$SCRIPT_DIR/.env"
TMP_DIR=""
DRY_RUN=N
ASSUME_YES=N
CONFIGURE=N

SERVER_NAME="localhost"
SERVER_ALIAS=""
SERVER_ROOT="/var/www"
SERVER_APP="html"
SERVER_TZ="Asia/Jakarta"
INSTALL_PHP=Y
INSTALL_PHP_VERSION=("8.4" "8.5")
INSTALL_NGINX=Y
INSTALL_APACHE=N
INSTALL_MARIADB=Y
INSTALL_REDIS=Y
INSTALL_PHPMYADMIN=N
INSTALL_NODEJS=Y
INSTALL_COMPOSER=Y
INSTALL_UV=N
INSTALL_DEV_TOOLS=Y
INSTALL_SHELL_CUSTOMIZATION=N
INSTALL_ADDONS=N
INSTALL_DB_NAMES=()
INSTALL_DB_USER=""
INSTALL_DB_PASSWORD=""
INSTALL_DB_POWER_USER=""
INSTALL_DB_POWER_PASS=""

cleanup_tmp() { [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]] && rm -rf -- "$TMP_DIR" || true; }
trap cleanup_tmp EXIT
trap 'printf "\nERROR: installer stopped while running: %s\n  (reported line %s is inside a helper function, not the call site)\n" "$BASH_COMMAND" "$LINENO" >&2' ERR

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
info() { printf '\n>>> %s\n' "$*"; }
is_yes() { [[ "${1:-N}" =~ ^[Yy]$ ]]; }
root() { if (( EUID == 0 )); then "$@"; else sudo "$@"; fi; }

usage() {
  cat <<'EOF'
Usage: ./install.sh [--yes] [--dry-run] [--configure]
  --yes        Use values from .env (or safe built-in defaults) without a prompt.
  --dry-run    Validate configuration and print the plan without changing the system.
  --configure  Open the interactive configuration wizard and save .env before continuing.
EOF
}

ui_init() {
  UI_BOLD="" UI_RESET="" UI_CYAN="" UI_GREEN="" UI_YELLOW=""
  [[ -t 1 && -n ${TERM:-} ]] && command -v tput >/dev/null 2>&1 || return 0
  UI_BOLD=$(tput bold 2>/dev/null || true)
  UI_RESET=$(tput sgr0 2>/dev/null || true)
  UI_CYAN=$(tput setaf 6 2>/dev/null || true)
  UI_GREEN=$(tput setaf 2 2>/dev/null || true)
  UI_YELLOW=$(tput setaf 3 2>/dev/null || true)
}
ui_title() {
  ui_init
  clear
  printf "\x1B[32m"
  printf '*%.0s' {1..100}
  printf "\n"
  printf "* %s\n" "Welcome to the PHP MariaDB Web Server Installer"
  printf "* %s\n" "This script will guide you to install the PHP MariaDB Web Server"
  printf "* %s\n" "on your WSL (Windows Subsystem for Linux) or Linux Machine"
  printf '*%.0s' {1..100}
  printf "\x1B[0m\n\n"
}
prompt_value() {
  local label=$1 current=$2 answer
  read -r -p "$label [$current]: " answer || answer=""
  printf '%s' "${answer:-$current}"
}
join_space() {
  local separator="" item
  for item in "$@"; do
    printf '%s%s' "$separator" "$item"
    separator=' '
  done
}
prompt_bool() {
  local label=$1 current=$2 answer hint
  [[ $current =~ ^[Yy]$ ]] && hint='Y/n' || hint='y/N'
  while :; do
    read -r -p "$label [$hint]: " answer || answer=""
    answer=${answer:-$current}
    valid_bool "$answer" && { printf '%s' "${answer^^}"; return 0; }
    printf 'Please enter Y or N.\n' >&2
  done
}
save_wizard_env() {
  local tmp db_lines
  tmp=$(mktemp "$SCRIPT_DIR/.env.wizard.XXXXXX")
  {
    printf '# Generated by the interactive installer. Database credentials remain local-only.\n'
    printf 'SERVER_NAME=%s\nSERVER_ALIAS=%s\nSERVER_ROOT=%s\nSERVER_APP=%s\nSERVER_TZ=%s\n' "$SERVER_NAME" "$SERVER_ALIAS" "$SERVER_ROOT" "$SERVER_APP" "$SERVER_TZ"
    printf 'INSTALL_PHP=%s\nINSTALL_PHP_VERSION="%s"\n' "$INSTALL_PHP" "$(join_space "${INSTALL_PHP_VERSION[@]}")"
    printf 'INSTALL_NGINX=%s\nINSTALL_APACHE=%s\nINSTALL_MARIADB=%s\nINSTALL_REDIS=%s\nINSTALL_PHPMYADMIN=%s\n' "$INSTALL_NGINX" "$INSTALL_APACHE" "$INSTALL_MARIADB" "$INSTALL_REDIS" "$INSTALL_PHPMYADMIN"
    printf 'INSTALL_NODEJS=%s\nINSTALL_COMPOSER=%s\nINSTALL_UV=%s\nINSTALL_DEV_TOOLS=%s\nINSTALL_SHELL_CUSTOMIZATION=%s\nINSTALL_ADDONS=%s\n' "$INSTALL_NODEJS" "$INSTALL_COMPOSER" "$INSTALL_UV" "$INSTALL_DEV_TOOLS" "$INSTALL_SHELL_CUSTOMIZATION" "$INSTALL_ADDONS"
    if [[ -f $ENV_FILE ]]; then
      grep -E '^INSTALL_DB_(NAMES|USER|PASSWORD|POWER_USER|POWER_PASS)=' "$ENV_FILE" || true
    else
      printf 'INSTALL_DB_NAMES=""\nINSTALL_DB_USER=""\nINSTALL_DB_PASSWORD=""\nINSTALL_DB_POWER_USER=""\nINSTALL_DB_POWER_PASS=""\n'
    fi
  } > "$tmp"
  chmod 600 "$tmp"
  mv -f "$tmp" "$ENV_FILE"
  info 'Saved non-secret choices to .env; existing database credentials were preserved.'
}
interactive_wizard() {
  [[ -t 0 ]] || die 'Interactive configuration requires a terminal. Edit .env or use --yes instead.'
  local php_versions web choice
  ui_title
  printf '%sInteractive setup — press Enter to keep the suggested value.%s\n' "$UI_GREEN" "$UI_RESET"
  SERVER_NAME=$(prompt_value 'Server name' "$SERVER_NAME")
  SERVER_ALIAS=$(prompt_value 'Server alias (blank for none)' "$SERVER_ALIAS")
  SERVER_ROOT=$(prompt_value 'Web root' "$SERVER_ROOT")
  SERVER_APP=$(prompt_value 'Web app directory' "$SERVER_APP")
  SERVER_TZ=$(prompt_value 'Timezone' "$SERVER_TZ")
  while :; do
    php_versions=$(prompt_value 'PHP versions (space-separated)' "$(join_space "${INSTALL_PHP_VERSION[@]}")")
    IFS=' ' read -r -a INSTALL_PHP_VERSION <<< "$php_versions"
    ((${#INSTALL_PHP_VERSION[@]})) && { for choice in "${INSTALL_PHP_VERSION[@]}"; do valid_php_version "$choice" || break; done; valid_php_version "$choice"; } && break
    printf 'Use supported versions: 5.6, 7.4, 8.1, 8.2, 8.3, 8.4, 8.5.\n' >&2
  done
  while :; do
    read -r -p 'Web server: [1] Nginx  [2] Apache [1]: ' web || web=''
    web=${web:-1}
    case "$web" in 1) INSTALL_NGINX=Y; INSTALL_APACHE=N; break ;; 2) INSTALL_NGINX=N; INSTALL_APACHE=Y; break ;; *) printf 'Choose 1 or 2.\n' >&2 ;; esac
  done
  INSTALL_MARIADB=$(prompt_bool 'Install MariaDB' "$INSTALL_MARIADB")
  INSTALL_REDIS=$(prompt_bool 'Install Redis' "$INSTALL_REDIS")
  INSTALL_PHPMYADMIN=$(prompt_bool 'Install phpMyAdmin' "$INSTALL_PHPMYADMIN")
  INSTALL_NODEJS=$(prompt_bool 'Install Node.js LTS' "$INSTALL_NODEJS")
  INSTALL_COMPOSER=$(prompt_bool 'Install Composer' "$INSTALL_COMPOSER")
  INSTALL_DEV_TOOLS=$(prompt_bool 'Install developer tools' "$INSTALL_DEV_TOOLS")
  INSTALL_UV=$(prompt_bool 'Install uv' "$INSTALL_UV")
  INSTALL_SHELL_CUSTOMIZATION=$(prompt_bool 'Install Oh My Zsh + Powerlevel10k' "$INSTALL_SHELL_CUSTOMIZATION")
  INSTALL_ADDONS=$(prompt_bool 'Run private addons when available' "$INSTALL_ADDONS")
  validate_config
  printf '\n%sConfiguration ready:%s PHP %s | Web: %s | MariaDB: %s | Redis: %s | phpMyAdmin: %s\n' "$UI_BOLD" "$UI_RESET" "$(join_space "${INSTALL_PHP_VERSION[@]}")" "$([[ $INSTALL_NGINX == Y ]] && printf Nginx || printf Apache)" "$INSTALL_MARIADB" "$INSTALL_REDIS" "$INSTALL_PHPMYADMIN"
  choice=$(prompt_bool 'Save this configuration to .env' Y)
  is_yes "$choice" || die 'Configuration was not saved.'
  save_wizard_env
}

confirm_or_configure() {
  local answer
  is_yes "$ASSUME_YES" && return 0
  while :; do
    read -r -p 'Continue [Y], Edit configuration [E], or Cancel [N]? ' answer || answer=''
    case "${answer:-Y}" in
      [Yy]) return 0 ;;
      [Ee]) interactive_wizard; validate_config; show_plan ;;
      [Nn]) printf 'Cancelled.\n'; return 1 ;;
      *) printf 'Choose Y, E, or N.\n' >&2 ;;
    esac
  done
}

strip_outer_quotes() {
  local value=$1
  if [[ ${#value} -ge 2 && ( ${value:0:1} == "'" && ${value: -1} == "'" || ${value:0:1} == '"' && ${value: -1} == '"' ) ]]; then
    value=${value:1:${#value}-2}
  fi
  printf '%s' "$value"
}

load_env() {
  [[ -f "$ENV_FILE" ]] || return 0
  [[ -L "$ENV_FILE" ]] && die '.env must not be a symlink.'
  local line key raw value
  while IFS= read -r line || [[ -n "$line" ]]; do
    line=${line%$'\r'}
    [[ -z "${line//[[:space:]]/}" || $line == \#* ]] && continue
    [[ $line == *=* ]] || die "Invalid .env line: $line"
    key=${line%%=*}
    raw=${line#*=}
    key=${key//[[:space:]]/}
    value=$(strip_outer_quotes "$raw")
    case "$key" in
      SERVER_NAME|SERVER_ALIAS|SERVER_ROOT|SERVER_APP|SERVER_TZ|INSTALL_PHP|INSTALL_NGINX|INSTALL_APACHE|INSTALL_MARIADB|INSTALL_REDIS|INSTALL_PHPMYADMIN|INSTALL_NODEJS|INSTALL_COMPOSER|INSTALL_UV|INSTALL_DEV_TOOLS|INSTALL_SHELL_CUSTOMIZATION|INSTALL_ADDONS|INSTALL_DB_USER|INSTALL_DB_PASSWORD|INSTALL_DB_POWER_USER|INSTALL_DB_POWER_PASS)
        printf -v "$key" '%s' "$value"
        ;;
      INSTALL_PHP_VERSION|INSTALL_DB_NAMES)
        value=${value#(}; value=${value%)}
        value=$(strip_outer_quotes "$value")
        if [[ $key == INSTALL_PHP_VERSION ]]; then IFS=' ' read -r -a INSTALL_PHP_VERSION <<< "$value"; else IFS=' ' read -r -a INSTALL_DB_NAMES <<< "$value"; fi
        ;;
      *) die "Unsupported .env key: $key" ;;
    esac
  done < "$ENV_FILE"
}

valid_bool() { [[ ${1:-} =~ ^[YyNn]$ ]]; }
valid_identifier() { [[ ${1:-} =~ ^[A-Za-z_][A-Za-z0-9_]{0,63}$ ]]; }
valid_aliases() {
  local alias
  [[ -z ${1:-} ]] && return 0
  local aliases=()
  read -r -a aliases <<< "$1"
  for alias in "${aliases[@]}"; do
    [[ $alias =~ ^([A-Za-z0-9][A-Za-z0-9-]*\.)+[A-Za-z]{2,63}$ ]] || return 1
  done
}
valid_php_version() { [[ ${1:-} =~ ^(5\.6|7\.4|8\.1|8\.2|8\.3|8\.4|8\.5)$ ]]; }

validate_config() {
  local key value
  for key in INSTALL_PHP INSTALL_NGINX INSTALL_APACHE INSTALL_MARIADB INSTALL_REDIS INSTALL_PHPMYADMIN INSTALL_NODEJS INSTALL_COMPOSER INSTALL_UV INSTALL_DEV_TOOLS INSTALL_SHELL_CUSTOMIZATION INSTALL_ADDONS; do
    value=${!key}; valid_bool "$value" || die "$key must be Y or N."
  done
  is_yes "$INSTALL_NGINX" && is_yes "$INSTALL_APACHE" && die 'Choose Nginx or Apache, not both: they share ports 80/443.'
  is_yes "$INSTALL_PHPMYADMIN" && ! is_yes "$INSTALL_PHP" && die 'phpMyAdmin requires INSTALL_PHP=Y.'
  is_yes "$INSTALL_COMPOSER" && ! is_yes "$INSTALL_PHP" && die 'Composer requires INSTALL_PHP=Y.'
  [[ $SERVER_NAME == localhost || $SERVER_NAME =~ ^([A-Za-z0-9][A-Za-z0-9-]*\.)+[A-Za-z]{2,63}$ ]] || die 'SERVER_NAME must be localhost or a valid FQDN.'
  valid_aliases "$SERVER_ALIAS" || die 'SERVER_ALIAS must be blank or valid FQDNs separated by spaces.'
  [[ $SERVER_ROOT == /* && $SERVER_ROOT != *$'\n'* ]] || die 'SERVER_ROOT must be an absolute path.'
  [[ $SERVER_APP =~ ^[A-Za-z0-9._-]+$ ]] || die 'SERVER_APP may contain only letters, digits, dot, underscore, and dash.'
  [[ -f "/usr/share/zoneinfo/$SERVER_TZ" ]] || die "Unknown SERVER_TZ: $SERVER_TZ"
  if is_yes "$INSTALL_PHP"; then
    ((${#INSTALL_PHP_VERSION[@]})) || die 'INSTALL_PHP_VERSION cannot be empty when PHP is enabled.'
    for value in "${INSTALL_PHP_VERSION[@]}"; do valid_php_version "$value" || die "Unsupported PHP version: $value"; done
  fi
  if ((${#INSTALL_DB_NAMES[@]})); then
    valid_identifier "$INSTALL_DB_USER" || die 'INSTALL_DB_USER must be a safe SQL identifier when databases are requested.'
    [[ -n $INSTALL_DB_PASSWORD ]] || die 'INSTALL_DB_PASSWORD is required when databases are requested.'
    for value in "${INSTALL_DB_NAMES[@]}"; do valid_identifier "$value" || die "Unsafe database name: $value"; done
  fi
  if [[ -n $INSTALL_DB_POWER_USER ]]; then
    valid_identifier "$INSTALL_DB_POWER_USER" || die 'INSTALL_DB_POWER_USER must be a safe SQL identifier.'
    [[ -n $INSTALL_DB_POWER_PASS ]] || die 'INSTALL_DB_POWER_PASS is required for INSTALL_DB_POWER_USER.'
  fi
}

preflight() {
  [[ ${BASH_VERSINFO[0]} -ge 5 ]] || die 'Bash 5+ is required.'
  [[ -r /etc/os-release ]] || die 'Only Debian/Ubuntu systems are supported.'
  . /etc/os-release
  [[ ${ID:-} == debian || ${ID:-} == ubuntu ]] || die "Unsupported OS: ${ID:-unknown}."
  if (( EUID == 0 )) && [[ -n ${SUDO_USER:-} && $SUDO_USER != root ]]; then
    die 'Do not run via sudo. Run ./install.sh as the regular user so user tools stay in that home directory.'
  fi
  if (( EUID != 0 )); then command -v sudo >/dev/null || die 'sudo is required for a regular-user install.'; sudo -v; fi
  command -v apt-get >/dev/null || die 'apt-get is required.'
  [[ -d "$SCRIPT_DIR/config" ]] || die 'Run from a complete project checkout.'
}

safe_source_private_addons() {
  local addon="$PRIVATE_DIR/scripts/addons.sh" mode owner
  is_yes "$INSTALL_ADDONS" || return 0
  [[ -f "$addon" ]] || { info 'Private addons requested but no private hook exists; skipped.'; return 0; }
  [[ ! -L "$addon" ]] || die 'Private addon hook must not be a symlink.'
  mode=$(stat -c '%a' "$addon")
  owner=$(stat -c '%u' "$addon")
  [[ $mode =~ ^[67]00$ ]] || die 'Private addon hook must be mode 600 or 700.'
  [[ $owner == $EUID ]] || die 'Private addon hook must be owned by the invoking user.'
  # This is intentionally a local extension point; only a trusted, private, owner-only file may be loaded.
  source "$addon"
}

# Restore per-user config from the private backup directory.
# Runs automatically when the hook file exists; it is a no-op unless those backups exist.
safe_source_private_restore() {
  local restore_hook="$PRIVATE_DIR/scripts/restore_config.sh" mode owner
  [[ -f "$restore_hook" ]] || return 0
  [[ ! -L "$restore_hook" ]] || die 'Private restore hook must not be a symlink.'
  mode=$(stat -c '%a' "$restore_hook")
  owner=$(stat -c '%u' "$restore_hook")
  [[ $mode =~ ^[67]00$ ]] || die 'Private restore hook must be mode 600 or 700.'
  [[ $owner == $EUID ]] || die 'Private restore hook must be owned by the invoking user.'
  source "$restore_hook"
}

latest_php() { printf '%s' "${INSTALL_PHP_VERSION[${#INSTALL_PHP_VERSION[@]}-1]}"; }
php_socket() { local ver; ver=$(latest_php); if [[ $INSTALL_NAME == server ]]; then printf '/run/php/php%s-fpm-pool1.sock' "$ver"; else printf '/run/php/php%s-fpm.sock' "$ver"; fi; }
private_or_public_file() { local rel=$1; [[ -f "$PRIVATE_DIR/$rel" ]] && printf '%s' "$PRIVATE_DIR/$rel" || printf '%s' "$SCRIPT_DIR/config/$rel"; }

package_plan() {
  PACKAGES=(bash-completion ca-certificates curl git nano openssl rsync xz-utils)
  if is_yes "$INSTALL_DEV_TOOLS"; then PACKAGES+=(bc dos2unix htop jq ncdu netcat-openbsd pigz pv tmux tree unzip); fi
  if is_yes "$INSTALL_SHELL_CUSTOMIZATION"; then PACKAGES+=(zsh); fi
  if is_yes "$INSTALL_PHP"; then
    local ver
    for ver in "${INSTALL_PHP_VERSION[@]}"; do
      PACKAGES+=("php$ver-bcmath" "php$ver-cli" "php$ver-common" "php$ver-curl" "php$ver-fpm" "php$ver-gd" "php$ver-intl" "php$ver-mbstring" "php$ver-mysql" "php$ver-xml" "php$ver-zip")
      is_yes "$INSTALL_REDIS" && PACKAGES+=("php$ver-redis")
    done
  fi
  is_yes "$INSTALL_NGINX" && PACKAGES+=(nginx)
  is_yes "$INSTALL_APACHE" && PACKAGES+=(apache2 apache2-utils)
  is_yes "$INSTALL_MARIADB" && PACKAGES+=(mariadb-server mysqltuner)
  is_yes "$INSTALL_REDIS" && PACKAGES+=(redis-server) || true
}

setup_php_repository() {
  is_yes "$INSTALL_PHP" || return 0
  . /etc/os-release
  if [[ $ID == ubuntu ]]; then
    root apt-get install -y software-properties-common
    root add-apt-repository -y ppa:ondrej/php
  else
    root install -d -m 0755 /usr/share/keyrings
    root curl -fsSL https://packages.sury.org/php/apt.gpg -o /usr/share/keyrings/deb.sury.org-php.gpg
    printf 'deb [signed-by=/usr/share/keyrings/deb.sury.org-php.gpg] https://packages.sury.org/php/ %s main\n' "$VERSION_CODENAME" | root tee /etc/apt/sources.list.d/php.list >/dev/null
  fi
}

ensure_shell_tool_env() {
  local shell_rc
  for shell_rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
    if [[ ! -f "$shell_rc" ]]; then
      if [[ "$shell_rc" == "$HOME/.bashrc" ]]; then
        : > "$shell_rc"
      else
        continue
      fi
    fi
    if ! grep -q '# >>> wsl2php user tools >>>' "$shell_rc"; then
      {
        printf '\n# >>> wsl2php user tools >>>\n'
        printf '# Added by wsl2php installer; safe to re-run.\n'
        printf 'export PATH="$HOME/.local/bin:$PATH"\n'
        printf 'export NVM_DIR="$HOME/.nvm"\n'
        printf '[[ -s "$NVM_DIR/nvm.sh" ]] && . "$NVM_DIR/nvm.sh"\n'
        printf '[[ -s "$NVM_DIR/bash_completion" ]] && . "$NVM_DIR/bash_completion"\n'
        printf '# <<< wsl2php user tools <<<\n'
      } >> "$shell_rc"
    fi
  done
}

install_user_tools() {
  TMP_DIR=$(mktemp -d)
  if is_yes "$INSTALL_NODEJS" && [[ ! -s "$HOME/.nvm/nvm.sh" ]]; then
    info 'Installing NVM for the current user'
    curl -fsSLo "$TMP_DIR/nvm-install.sh" https://raw.githubusercontent.com/nvm-sh/nvm/v0.40.6/install.sh
    bash "$TMP_DIR/nvm-install.sh"
  fi
  if is_yes "$INSTALL_UV" && ! command -v uv >/dev/null; then
    info 'Installing uv for the current user'
    curl -fsSLo "$TMP_DIR/uv-install.sh" https://astral.sh/uv/0.12.0/install.sh
    sh "$TMP_DIR/uv-install.sh"
    export PATH="$HOME/.local/bin:$PATH"
  fi
  if is_yes "$INSTALL_NODEJS"; then
    export NVM_DIR="$HOME/.nvm"
    [[ -s "$NVM_DIR/nvm.sh" ]] || die 'NVM installation did not produce nvm.sh.'
    . "$NVM_DIR/nvm.sh"
    nvm install --lts
    npm install -g npm@latest
  fi
  ensure_shell_tool_env
}

install_composer() {
  is_yes "$INSTALL_COMPOSER" || return 0
  TMP_DIR=${TMP_DIR:-$(mktemp -d)}
  local expected actual
  expected=$(curl -fsSL https://composer.github.io/installer.sha384sum | awk '{print $1}')
  [[ $expected =~ ^[a-f0-9]{96}$ ]] || die 'Could not obtain Composer installer checksum.'
  curl -fsSLo "$TMP_DIR/composer-setup.php" https://getcomposer.org/installer
  actual=$(sha384sum "$TMP_DIR/composer-setup.php" | awk '{print $1}')
  [[ $actual == "$expected" ]] || die 'Composer installer checksum mismatch.'
  php "$TMP_DIR/composer-setup.php" --quiet --install-dir="$TMP_DIR" --filename=composer
  root install -m 0755 "$TMP_DIR/composer" /usr/local/bin/composer
}

install_phpmyadmin() {
  is_yes "$INSTALL_PHPMYADMIN" || return 0
  local version=5.2.3 archive="phpMyAdmin-5.2.3-english.tar.gz" expected=03de2640bb25c9a6f96bc94eae316080b5fd5bd58d769e1318ba9dd94c83364c
  TMP_DIR=${TMP_DIR:-$(mktemp -d)}
  info "Installing phpMyAdmin $version"
  curl -fsSLo "$TMP_DIR/$archive" "https://files.phpmyadmin.net/phpMyAdmin/$version/$archive"
  printf '%s  %s\n' "$expected" "$TMP_DIR/$archive" | sha256sum -c -
  tar -xzf "$TMP_DIR/$archive" -C "$TMP_DIR"
  [[ -d "$TMP_DIR/phpMyAdmin-$version-english" ]] || die 'phpMyAdmin archive layout changed.'
  root rm -rf /usr/share/phpmyadmin.new
  root mv "$TMP_DIR/phpMyAdmin-$version-english" /usr/share/phpmyadmin.new
  root chown -R root:root /usr/share/phpmyadmin.new
  root install -d -o www-data -g www-data -m 0750 /usr/share/phpmyadmin.new/tmp
  [[ -d /usr/share/phpmyadmin ]] && root mv /usr/share/phpmyadmin /usr/share/phpmyadmin.previous
  root mv /usr/share/phpmyadmin.new /usr/share/phpmyadmin
  root rm -rf /usr/share/phpmyadmin.previous
}

sed_escape() { sed -e 's/[\\&|]/\\&/g' <<< "$1"; }
render_template() {
  local source=$1 destination=$2 socket=$3 http2_listen=$4 http2_directive=$5 pma_include=$6
  sed \
    -e "s|__SERVER_NAME__|$(sed_escape "$SERVER_NAME")|g" \
    -e "s|__SERVER_ALIAS__|$(sed_escape "$SERVER_ALIAS")|g" \
    -e "s|__SERVER_ROOT__|$(sed_escape "$SERVER_ROOT")|g" \
    -e "s|__SERVER_APP__|$(sed_escape "$SERVER_APP")|g" \
    -e "s|__PHP_SOCKET__|$(sed_escape "$socket")|g" \
    -e "s|__HTTP2_LISTEN__|$http2_listen|g" \
    -e "s|__HTTP2_DIRECTIVE__|$http2_directive|g" \
    -e "s|__PMA_INCLUDE__|$pma_include|g" \
    "$source" > "$destination"
}

prepare_certificate() {
  local stage=$1 cert key chain
  cert="$PRIVATE_DIR/ssl/$SERVER_NAME.pem"
  key="$PRIVATE_DIR/ssl/$SERVER_NAME.key"
  chain="$PRIVATE_DIR/ssl/chain.pem"
  if [[ -f $cert && -f $key ]]; then
    cp "$cert" "$stage/$SERVER_NAME.pem"; cp "$key" "$stage/$SERVER_NAME.key"
    if [[ -f $chain ]]; then cp "$chain" "$stage/chain.pem"; fi
  elif [[ $SERVER_NAME == localhost ]]; then
    openssl req -x509 -newkey rsa:2048 -sha256 -nodes -days 365 -subj '/CN=localhost' \
      -keyout "$stage/localhost.key" -out "$stage/localhost.pem" >/dev/null 2>&1
  else
    die "Missing private SSL certificate/key for $SERVER_NAME under config/private/ssl/."
  fi
}

config_php() {
  local ver source
  for ver in "${INSTALL_PHP_VERSION[@]}"; do
    source="$SCRIPT_DIR/config/php/$INSTALL_NAME/$ver"
    [[ -d $source ]] || die "Missing PHP template: $source"
    root install -d -m 0755 "/etc/php/$ver/fpm/pool.d"
    root rm -f "/etc/php/$ver/fpm/pool.d"/*.conf
    root cp -a "$source/fpm/." "/etc/php/$ver/fpm/"
    root sed -i -E "s|^date.timezone\s*=.*|date.timezone = $SERVER_TZ|; s|^session.cookie_httponly\s*=.*|session.cookie_httponly = On|; s|^session.cookie_secure\s*=.*|session.cookie_secure = On|; s|^session.cookie_samesite\s*=.*|session.cookie_samesite = Lax|" "/etc/php/$ver/fpm/php.ini"
    if is_yes "$INSTALL_REDIS"; then
      root sed -i -E 's|^session.save_handler\s*=.*|session.save_handler = redis|; s|^;?session.save_path\s*=.*|session.save_path = "/run/redis/redis-server.sock?persistent=1"|' "/etc/php/$ver/fpm/php.ini"
    fi
    root chmod 0644 "/etc/php/$ver/fpm/pool.d"/*.conf
  done
}

config_nginx() {
  local stage source site socket http2_listen http2_directive pma_include
  stage=$(mktemp -d); TMP_DIR=${TMP_DIR:-$stage}
  prepare_certificate "$stage"
  root install -d -m 0755 /etc/nginx/ssl /etc/nginx/sites-available /etc/nginx/sites-enabled
  root cp "$stage/$SERVER_NAME.pem" "/etc/nginx/ssl/$SERVER_NAME.pem"
  root cp "$stage/$SERVER_NAME.key" "/etc/nginx/ssl/$SERVER_NAME.key"
  if [[ -f $stage/chain.pem ]]; then root sh -c "cat '/etc/nginx/ssl/$SERVER_NAME.pem' '$stage/chain.pem' > '/etc/nginx/ssl/$SERVER_NAME.crt'"; else root cp "/etc/nginx/ssl/$SERVER_NAME.pem" "/etc/nginx/ssl/$SERVER_NAME.crt"; fi
  root chmod 0600 "/etc/nginx/ssl/$SERVER_NAME.key"
  root chmod 0644 "/etc/nginx/ssl/$SERVER_NAME.pem" "/etc/nginx/ssl/$SERVER_NAME.crt"
  if [[ ! -f /etc/nginx/dhparam.pem ]]; then root openssl dhparam -out /etc/nginx/dhparam.pem 2048; fi
  source="$SCRIPT_DIR/config/nginx/$INSTALL_NAME.conf"
  [[ -f "$PRIVATE_DIR/nginx/$SERVER_NAME.conf" ]] && source="$PRIVATE_DIR/nginx/$SERVER_NAME.conf"
  [[ -f $source ]] || die "Missing Nginx site template: $source"
  socket=$(php_socket)
  if nginx -v 2>&1 | grep -Eq 'nginx/[1-9]\.(2[5-9]|[3-9][0-9])\.'; then http2_listen=""; http2_directive="http2 on;"; else http2_listen="http2"; http2_directive=""; fi
  pma_include="# phpMyAdmin disabled"
  is_yes "$INSTALL_PHPMYADMIN" && pma_include="include conf-phpmyadmin.conf;"
  render_template "$source" "$stage/site.conf" "$socket" "$http2_listen" "$http2_directive" "$pma_include"
  root cp "$SCRIPT_DIR/config/nginx/localhost.nginx.conf" /etc/nginx/nginx.conf
  # Install every shipped include fragment (conf-*.conf) so a private site template
  # can reference any of them. phpMyAdmin is rendered below, never copied raw.
  local fragment
  for fragment in "$SCRIPT_DIR"/config/nginx/conf-*.conf; do
    if [[ -f $fragment && ${fragment##*/} != conf-phpmyadmin.conf ]]; then root install -m 0644 "$fragment" "/etc/nginx/${fragment##*/}"; fi
  done
  render_template "$SCRIPT_DIR/config/nginx/conf-phpmyadmin.conf" "$stage/conf-phpmyadmin.conf" "$socket" "" "" ""
  root install -m 0644 "$stage/conf-phpmyadmin.conf" /etc/nginx/conf-phpmyadmin.conf
  root cp "$stage/site.conf" "/etc/nginx/sites-available/$SERVER_NAME.conf"
  root ln -sfn "/etc/nginx/sites-available/$SERVER_NAME.conf" "/etc/nginx/sites-enabled/$SERVER_NAME.conf"
  root rm -f /etc/nginx/sites-enabled/default
  root nginx -t
}

config_apache() {
  local stage source
  stage=$(mktemp -d); TMP_DIR=${TMP_DIR:-$stage}; prepare_certificate "$stage"
  source="$SCRIPT_DIR/config/apache/$INSTALL_NAME.conf"
  [[ -f $source ]] || die "Missing Apache site template: $source"
  root install -d -m 0755 /etc/apache2/ssl
  if [[ -f $stage/chain.pem ]]; then
    root sh -c "cat '$stage/$SERVER_NAME.pem' '$stage/chain.pem' > '/etc/apache2/ssl/$SERVER_NAME.crt'"
    root chmod 0644 "/etc/apache2/ssl/$SERVER_NAME.crt"
  else
    root install -m 0644 "$stage/$SERVER_NAME.pem" "/etc/apache2/ssl/$SERVER_NAME.crt"
  fi
  root install -m 0600 "$stage/$SERVER_NAME.key" "/etc/apache2/ssl/$SERVER_NAME.key"
  render_template "$source" "$stage/site.conf" "" "" "" ""
  root install -m 0644 "$stage/site.conf" "/etc/apache2/sites-available/$SERVER_NAME.conf"
  root a2enmod proxy_fcgi setenvif rewrite ssl headers http2
  root a2dissite 000-default.conf || true
  root a2ensite "$SERVER_NAME.conf"
  if is_yes "$INSTALL_PHP"; then root a2enconf "php$(latest_php)-fpm"; fi
  root apache2ctl configtest
}

sql_literal() { local value=$1; value=${value//\'/\'\'}; printf "'%s'" "$value"; }
run_sql() { printf '%s\n' "$1" | root mariadb; }

config_mariadb() {
  local source db
  source=$(private_or_public_file "mysql/$INSTALL_NAME.my.cnf")
  [[ -f $source ]] || source="$SCRIPT_DIR/config/mysql/localhost.my.cnf"
  root install -d -m 0755 /etc/mysql/mariadb.conf.d
  root install -m 0644 "$source" /etc/mysql/mariadb.conf.d/99-wsl2php.cnf
  root mariadbd --defaults-file=/etc/mysql/mariadb.conf.d/99-wsl2php.cnf --help --verbose >/dev/null
  service_action mariadb restart
  run_sql 'SELECT 1;'
  for db in "${INSTALL_DB_NAMES[@]}"; do
    run_sql "CREATE DATABASE IF NOT EXISTS \`$db\` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
    run_sql "CREATE USER IF NOT EXISTS '$INSTALL_DB_USER'@'localhost' IDENTIFIED BY $(sql_literal "$INSTALL_DB_PASSWORD"); GRANT ALL PRIVILEGES ON \`$db\`.* TO '$INSTALL_DB_USER'@'localhost';"
  done
  if [[ -n $INSTALL_DB_POWER_USER ]]; then
    run_sql "CREATE USER IF NOT EXISTS '$INSTALL_DB_POWER_USER'@'localhost' IDENTIFIED BY $(sql_literal "$INSTALL_DB_POWER_PASS"); GRANT ALL PRIVILEGES ON *.* TO '$INSTALL_DB_POWER_USER'@'localhost' WITH GRANT OPTION;"
  fi
  run_sql 'FLUSH PRIVILEGES;'
}

config_redis() {
  root sed -i -E 's|^#? ?unixsocket .*|unixsocket /run/redis/redis-server.sock|; s|^unixsocketperm .*|unixsocketperm 770|' /etc/redis/redis.conf
  root usermod -aG redis www-data
  service_action redis-server restart
}

config_phpmyadmin() {
  local secret
  secret=$(openssl rand -hex 16)
  printf '%s\n' "<?php" "\$cfg['blowfish_secret'] = '$secret';" "\$cfg['Servers'][1]['auth_type'] = 'cookie';" "\$cfg['TempDir'] = '/usr/share/phpmyadmin/tmp';" > "$TMP_DIR/config.inc.php"
  root install -o root -g www-data -m 0640 "$TMP_DIR/config.inc.php" /usr/share/phpmyadmin/config.inc.php
}

config_environment() {
  local ssh_src=""
  install -m 0644 "$SCRIPT_DIR/config/.bash_aliases" "$HOME/.bash_aliases"
  [[ -f "$PRIVATE_DIR/bash_aliases" ]] && cat "$PRIVATE_DIR/bash_aliases" >> "$HOME/.bash_aliases"
  chmod 0644 "$HOME/.bash_aliases"
  [[ -d "$PRIVATE_DIR/ssh" ]] && ssh_src="$PRIVATE_DIR/ssh"
  [[ -z "$ssh_src" && -d "$SCRIPT_DIR/config/.ssh" ]] && ssh_src="$SCRIPT_DIR/config/.ssh"
  if [[ -n $ssh_src ]]; then
    install -d -m 0700 "$HOME/.ssh" "$HOME/.ssh/keys" "$HOME/.ssh/config.d"
    rsync -a "$ssh_src/" "$HOME/.ssh/"
    chmod 0700 "$HOME/.ssh" "$HOME/.ssh/keys" "$HOME/.ssh/config.d"
    find "$HOME/.ssh" -type f -name '*.pub' -exec chmod 0644 {} +
    find "$HOME/.ssh" -type f ! -name '*.pub' -exec chmod 0600 {} +
  fi
  if is_yes "$INSTALL_SHELL_CUSTOMIZATION" && [[ -f "$SCRIPT_DIR/config/.zshrc" ]]; then
    if [[ ! -d "$HOME/.oh-my-zsh" ]]; then
      info 'Installing Oh My Zsh and plugins'
      sh -c "$(curl -fsSL https://raw.github.com/ohmyzsh/ohmyzsh/master/tools/install.sh)" "" --unattended
      git clone https://github.com/zsh-users/zsh-syntax-highlighting.git "$HOME/.oh-my-zsh/custom/plugins/zsh-syntax-highlighting"
      git clone https://github.com/zsh-users/zsh-autosuggestions "$HOME/.oh-my-zsh/custom/plugins/zsh-autosuggestions"
      git clone https://github.com/zsh-users/zsh-completions "$HOME/.oh-my-zsh/custom/plugins/zsh-completions"
      git clone --depth=1 https://github.com/romkatv/powerlevel10k.git "$HOME/.oh-my-zsh/custom/themes/powerlevel10k"
      root chsh -s "$(which zsh)" "$USER"
    fi
    install -m 0644 "$SCRIPT_DIR/config/.zshrc" "$HOME/.zshrc"
    ensure_shell_tool_env
    install -m 0644 "$SCRIPT_DIR/config/.p10k.zsh" "$HOME/.p10k.zsh"
  fi
}

config_timezone() {
  root timedatectl set-timezone "$SERVER_TZ" 2>/dev/null || root ln -sfn "/usr/share/zoneinfo/$SERVER_TZ" /etc/localtime
}

service_action() {
  local service=$1 action=$2
  if [[ -d /run/systemd/system ]]; then root systemctl "$action" "$service"; else root service "$service" "$action"; fi
}

enable_services() {
  [[ -d /run/systemd/system ]] || return 0
  is_yes "$INSTALL_NGINX" && root systemctl enable nginx
  is_yes "$INSTALL_APACHE" && root systemctl enable apache2
  is_yes "$INSTALL_MARIADB" && root systemctl enable mariadb
  is_yes "$INSTALL_REDIS" && root systemctl enable redis-server
  local ver; for ver in "${INSTALL_PHP_VERSION[@]}"; do if is_yes "$INSTALL_PHP"; then root systemctl enable "php$ver-fpm"; fi; done
}

verify_services() {
  info 'Verifying installed services'
  is_yes "$INSTALL_NGINX" && root nginx -t
  is_yes "$INSTALL_APACHE" && root apache2ctl configtest
  local ver
  if is_yes "$INSTALL_PHP"; then for ver in "${INSTALL_PHP_VERSION[@]}"; do root "php-fpm$ver" -tt >/dev/null; done; fi
  is_yes "$INSTALL_MARIADB" && root mariadb-admin ping --silent
  if is_yes "$INSTALL_REDIS"; then root redis-cli -s /run/redis/redis-server.sock ping | grep -qx PONG; fi
}

